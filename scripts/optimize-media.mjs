/**
 * Converts the legacy JPEG/PNG media into responsive WebP sets and writes a
 * typed manifest with intrinsic dimensions + inline blur placeholders.
 *
 * The site is a static export with `images.unoptimized`, so every size a
 * browser might pick has to exist on disk before the build. Run it with
 * `npm run media`; it is idempotent.
 */
import { mkdir, readdir, writeFile, stat } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const SOURCE = path.resolve('_source-media')
const OUT = path.resolve('public/media')
const MANIFEST = path.resolve('src/content/generated/media.ts')

/** Widths emitted per image. Anything wider than the source is skipped. */
const WIDTHS = [480, 768, 1200, 1800]

/** Folders whose images are shown full-bleed and deserve the largest step. */
const FULL_BLEED = new Set(['hero'])

const isRaster = (f) => /\.(jpe?g|png)$/i.test(f)

async function walk(dir, base = '') {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = path.join(base, entry.name)
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), rel)))
    else out.push(rel)
  }
  return out
}

/** A 16px-wide WebP, inlined as a data URI for the blur-up placeholder. */
async function blurPlaceholder(pipeline) {
  const buf = await pipeline
    .clone()
    .resize(16, null, { fit: 'inside' })
    .webp({ quality: 40 })
    .toBuffer()
  return `data:image/webp;base64,${buf.toString('base64')}`
}

async function main() {
  const files = (await walk(SOURCE)).filter(isRaster)
  const entries = []
  let savedBytes = 0

  for (const rel of files) {
    const src = path.join(SOURCE, rel)
    const dirname = path.dirname(rel) === '.' ? '' : path.dirname(rel)
    const name = path.basename(rel).replace(/\.(jpe?g|png)$/i, '')
    const outDir = path.join(OUT, dirname)
    await mkdir(outDir, { recursive: true })

    const pipeline = sharp(src)
    const meta = await pipeline.metadata()
    const originalBytes = (await stat(src)).size

    const cap = FULL_BLEED.has(dirname) ? 2400 : 1800
    const widths = WIDTHS.filter((w) => w <= Math.min(meta.width, cap))
    // Always emit at least one size, even for small source images.
    if (widths.length === 0) widths.push(meta.width)
    // Emit the capped full-size step for hero art so large displays stay sharp.
    if (meta.width > 1800 && cap === 2400 && !widths.includes(2400)) widths.push(2400)

    let emitted = 0
    for (const w of widths) {
      const dest = path.join(outDir, `${name}-${w}.webp`)
      if (!existsSync(dest)) {
        await pipeline.clone().resize(w, null, { withoutEnlargement: true }).webp({ quality: 78 }).toFile(dest)
      }
      emitted += (await stat(dest)).size
    }

    savedBytes += originalBytes - emitted
    entries.push({
      key: path.join(dirname, name).split(path.sep).join('/'),
      dir: dirname,
      name,
      width: meta.width,
      height: meta.height,
      widths,
      blur: await blurPlaceholder(pipeline),
    })
  }

  entries.sort((a, b) => a.key.localeCompare(b.key))

  const body = entries
    .map(
      (e) => `  '${e.key}': {
    src: '/media/${e.key}-${e.widths[e.widths.length - 1]}.webp',
    srcSet: '${e.widths.map((w) => `/media/${e.key}-${w}.webp ${w}w`).join(', ')}',
    width: ${e.width},
    height: ${e.height},
    blurDataURL:
      '${e.blur}',
  },`
    )
    .join('\n')

  const file = `// GENERATED by scripts/optimize-media.mjs — do not edit by hand.
// Run \`npm run media\` after adding images to _source-media/.

export type MediaAsset = {
  src: string
  srcSet: string
  width: number
  height: number
  blurDataURL: string
}

export const media = {
${body}
} as const satisfies Record<string, MediaAsset>

export type MediaKey = keyof typeof media
`

  await mkdir(path.dirname(MANIFEST), { recursive: true })
  await writeFile(MANIFEST, file, 'utf8')

  console.log(`✓ ${entries.length} images → ${OUT}`)
  console.log(`✓ manifest → ${path.relative(process.cwd(), MANIFEST)}`)
  console.log(`✓ saved ~${(savedBytes / 1024 / 1024).toFixed(1)} MB vs originals`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
